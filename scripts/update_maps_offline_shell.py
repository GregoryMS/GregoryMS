#!/usr/bin/env python3
"""Keep the offline shell in lockstep with versioned Maps HTML dependencies."""
import hashlib
import json
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
html = (root / 'maps.html').read_text()
assets = set()
for tag, reference in re.findall(r'(<(?:script|link)\b[^>]*\b(?:src|href)="([^"]+)"[^>]*>)', html):
    if tag.startswith('<link') and not re.search(r'rel="(?:stylesheet|manifest|icon|apple-touch-icon)"', tag):
        continue
    if reference.startswith(('https:', '//')):
        # Google Fonts are decorative; the local font stack works without them.
        if 'fonts.googleapis.com' in reference:
            continue
        raise ValueError('External required dependency: ' + reference)
    assets.add('/' + reference.lstrip('/'))
assets.update('/'+p for p in ['assets/maps-config.json?v=20261112-search-proxy',
    'assets/maps-offline-worker.js', 'assets/maps-offline-routing.js', 'assets/maps-offline-data-worker.js',
    'assets/maps-offline-store.js', 'assets/maps-navigation-core.js',
    'assets/vendor/leaflet/images/marker-icon.png', 'assets/vendor/leaflet/images/marker-icon-2x.png',
    'assets/vendor/leaflet/images/marker-shadow.png', 'assets/vendor/leaflet/images/layers.png',
    'assets/vendor/leaflet/images/layers-2x.png', 'assets/fonts/gregle-wordmark-300.woff?v=20261102-heading1'])
# Lazy renderer, worker imports, styles, fonts and sprites must be available offline.
assets.update('/'+p for p in ['assets/vendor/maplibre/maplibre-gl.js', 'assets/leaflet-maplibre-gl.js',
    'assets/vendor/pmtiles/tile-search.js'])
assets.update('/'+str(p.relative_to(root)) for p in (root/'assets/maps-offline-style').rglob('*')
              if p.is_file() and p.suffix in {'.json', '.png', '.pbf'})
# Include local CSS url dependencies as well.
for ref in list(assets):
    path=root/ref.lstrip('/').split('?')[0]
    if not path.is_file():
        raise FileNotFoundError(path)
    if path.suffix == '.css':
        for value in re.findall(r'url\([\'\"]?([^\)\'\"]+)',path.read_text()):
            if value.startswith(('data:', 'https:', '//', '#')):
                continue
            url=str((path.parent/value.split('?')[0]).resolve().relative_to(root))
            assets.add('/'+url+('?' + value.split('?',1)[1] if '?' in value else ''))
content=html.encode()+b''.join((root/p.lstrip('/').split('?')[0]).read_bytes() for p in sorted(assets))
version=hashlib.sha256(content).hexdigest()[:16]
(root/'assets/maps-offline-shell.js').write_text('/* Generated by scripts/update_maps_offline_shell.py. */\nself.GregleMapsShell='+json.dumps({'version':version,'assets':sorted(assets)},separators=(',',':'))+';\n')
