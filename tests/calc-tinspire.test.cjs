const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const {gunzipSync}=require('node:zlib');
const {pathToFileURL}=require('node:url');
const {diagnosticFirmware}=require('./tinspire-fixture.cjs');
const directory=path.join(__dirname,'../assets/tinspire');
const load=filename=>import(pathToFileURL(path.join(directory,filename)));
async function engine(boot,flash,state) {
  const {default:create}=await load('firebird.mjs');
  const core=await create({wasmBinary:fs.readFileSync(path.join(directory,'firebird.wasm')),print(){},printErr(){}});
  core.FS.writeFile('/boot1.img',boot); core.FS.writeFile('/flash.img',flash);
  if (state) core.FS.writeFile('/session.bin',state);
  assert.equal(core._gregle_start(state?1:0),1);
  return core;
}
test('real Firebird WebAssembly executes ARM instructions and resumes complete CPU/RAM/peripheral snapshots',async()=>{
  const {boot,flash}=diagnosticFirmware(), core=await engine(boot,flash);
  assert.equal(core._gregle_save(),1);
  const before=gunzipSync(core.FS.readFile('/session.bin'));
  for (let i=0;i<4;i++) assert.equal(core._gregle_step(),1);
  assert.equal(core._gregle_save(),1);
  const state=core.FS.readFile('/session.bin'), after=gunzipSync(state);
  const registers=Buffer.from([0,0,0,0x10,42,0,0,0,0,0,0,0]);
  assert.equal(before.indexOf(registers),-1);
  assert(after.indexOf(registers)>1032,'R0/R1 contain the values written by our ARM program');
  assert(after.length>65*1024*1024,'snapshot contains all emulated memory and peripherals');
  const pointer=core._gregle_frame();
  assert(pointer>0 && pointer+320*240*4<=core.HEAPU8.length);
  assert.equal(core.HEAPU8[pointer+3],255);
  const restored=await engine(boot,flash,state);
  assert.equal(restored._gregle_save(),1);
  assert.deepEqual(gunzipSync(restored.FS.readFile('/session.bin')),after);
  restored._gregle_key(4,6,1); restored._gregle_touch(.5,0,1,1);
  assert.equal(restored._gregle_save(),1);
  assert.notDeepEqual(restored.FS.readFile('/session.bin'),state,'key matrix and touchpad state reach the real core');
  restored._gregle_key(4,6,0); restored._gregle_touch(.5,0,0,0);
  assert.equal(restored._gregle_step(),1);
});
test('firmware packing round trips and rejects missing, wrong-model, empty and damaged images',async()=>{
  const {packFirmware,unpackFirmware}=await load('firmware.mjs');
  const {boot,flash}=diagnosticFirmware();
  const bundle=packFirmware(boot,flash), files=unpackFirmware(bundle);
  assert.deepEqual(files.boot,boot); assert.deepEqual(files.flash,flash);
  assert.throws(()=>packFirmware(new Uint8Array(8),flash),/Boot1/);
  assert.throws(()=>packFirmware(boot,new Uint8Array(1024)),/flash image/);
  assert.throws(()=>packFirmware(new Uint8Array(0x80000),flash),/empty or damaged/);
  new DataView(flash.buffer).setUint16(0x844,0x10,true);
  assert.throws(()=>packFirmware(boot,flash),/not for the TI-Nspire CX CAS/);
  assert.throws(()=>unpackFirmware(bundle.slice(0,-1)),/damaged/);
});
test('Nspire layout maps all physical keys exactly once and includes A–Z and five touchpad regions',()=>{
  let layout;
  vm.runInNewContext(fs.readFileSync(path.join(directory,'../calc-tinspire.js'),'utf8'),{window:{createGregleEmulator(value){layout=value;}}});
  const keys=[...layout.menus,...layout.controls,...layout.keys,...layout.alphaKeys];
  assert.equal(new Set(keys.map(key=>`${key[2]}:${key[3]}`)).size,keys.length);
  assert.equal(layout.alphaKeys.length,33);
  assert.deepEqual(Array.from(layout.alphaKeys.filter(key=>/^[a-z]$/.test(key[0])),key=>key[0]),'abcdefghijklmnopqrstuvwxyz'.split(''));
  assert(layout.arrows.every(key=>key[2]===8));
  assert.equal(layout.keyMap.Control,'ctrl'); assert.equal(layout.keyMap.PageDown,'menu');
  const html=layout.renderLayout(key=>`<key name="${key[0]}"></key>`);
  assert.match(html,/<key name="equal"><\/key><key name="trig"><\/key>/);
  assert.match(html,/<key name="multiply"><\/key><key name="divide"><\/key>/);
  assert.match(html,/nspire-touchpad/);
  assert.match(html,/<key name="ee"><\/key><key name="a"><\/key>/);
});
test('touchpad separates pointer movement from taps and releases held clicks on cancellation',()=>{
  let layout,next=0; const timers=new Map(),listeners={},messages=[];
  const marker={style:{},hidden:true},surface={style:{},classList:{toggle(){}},querySelector(){return marker;},addEventListener(type,fn){listeners[type]=fn;},getBoundingClientRect(){return {left:0,top:0,width:100,height:100};},focus(){},setPointerCapture(){}};
  vm.runInNewContext(fs.readFileSync(path.join(directory,'../calc-tinspire.js'),'utf8'),{window:{createGregleEmulator(value){layout=value;}},setTimeout(fn){timers.set(++next,fn);return next;},clearTimeout(id){timers.delete(id);}});
  const release=layout.bindTouchpad(surface,data=>messages.push(data));
  const event=(x,y)=>({pointerId:1,clientX:x,clientY:y,pointerType:'touch',button:0,preventDefault(){}});
  listeners.pointerdown(event(50,50));listeners.pointermove(event(80,50));listeners.pointerup(event(80,50));
  assert(messages.some(x=>x.x===.8 && x.contact && !x.down));assert(!messages.some(x=>x.down),'dragging moves the pointer without clicking');
  messages.length=0;listeners.pointerdown(event(50,5));listeners.pointerup(event(50,5));
  assert(messages.some(x=>x.x===.5 && x.y===0 && x.down),'top-edge tap sends a direction click');
  for (const fn of [...timers.values()]) fn();timers.clear();
  assert.equal(messages.at(-1).contact,false);
  listeners.pointerdown(event(50,50));for (const fn of [...timers.values()]) fn();timers.clear();
  assert.equal(messages.at(-1).down,true);listeners.pointercancel(event(50,50));
  assert.equal(messages.at(-1).down,false);assert.equal(marker.hidden,true);
  release();assert.equal(messages.at(-1).contact,false);
});
